import csv
import os
from datetime import timedelta
from django.conf import settings
from django.core.mail import EmailMessage
from django.db.models import Count
from django.utils import timezone
from alerts.models import Alert

try:
    import openpyxl
    HAS_OPENPYXL = True
except ImportError:
    HAS_OPENPYXL = False

try:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.units import mm
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.platypus import SimpleDocTemplate, Table, TableStyle, Paragraph, Spacer
    HAS_REPORTLAB = True
except ImportError:
    HAS_REPORTLAB = False

REPORTS_DIR = os.path.join(settings.MEDIA_ROOT, 'reports')
PERIOD_DAYS = {'DAILY': 1, 'WEEKLY': 7, 'MONTHLY': 30, 'YEARLY': 365}

BRAND_NAVY = '#0f172a'
BRAND_BLUE = '#1e40af'
BRAND_ACCENT = '#3b82f6'
BRAND_DARK = '#0f172a'
BRAND_GRAY = '#64748b'
BRAND_LIGHTGRAY = '#94a3b8'
BRAND_BORDER = '#cbd5e1'
BRAND_BG_LIGHT = '#f8fafc'
COMPANY_NAME = 'Akij Group'
TEAM_NAME = 'Cybersecurity Division'
REPORT_TAGLINE = 'Security Operations Center'


def _generated_by_label(generated_by):
    if generated_by is None:
        return 'Automated Scheduler'
    name = generated_by.get_full_name() or generated_by.username
    role = None
    profile = getattr(generated_by, 'analyst_profile', None)
    if profile is not None:
        role = profile.get_role_display()
    return f'{name} ({role})' if role else name


def is_due(report, now):
    if not report.last_generated_at:
        return True
    days = PERIOD_DAYS.get(report.schedule, 1)
    return (now - report.last_generated_at) > timedelta(days=days)


def _queryset(report, since):
    qs = Alert.objects.filter(alert_time__gte=since).select_related('assignee')
    if report.report_type == 'TP':
        qs = qs.filter(verdict='True Positive')
    elif report.report_type == 'FP':
        qs = qs.filter(verdict='False Positive')
    elif report.report_type == 'SLA':
        qs = qs.filter(sla_status='Breached')
    return qs


def _rows(report, qs):
    if report.report_type == 'ANALYST':
        headers = ['Analyst', 'Alerts Assigned']
        grouped = (qs.exclude(assignee__isnull=True)
                     .values('assignee__username')
                     .annotate(total=Count('id'))
                     .order_by('-total'))
        rows = [(g['assignee__username'], g['total']) for g in grouped]
    else:
        headers = ['Metric', 'Count']
        rows = [
            ('Total Alerts', qs.count()),
            ('Critical', qs.filter(severity='Critical').count()),
            ('High', qs.filter(severity='High').count()),
            ('Medium', qs.filter(severity='Medium').count()),
            ('Low', qs.filter(severity='Low').count()),
            ('Open', qs.filter(status__in=['New', 'In Progress']).count()),
            ('Closed', qs.filter(status='Closed').count()),
            ('True Positives', qs.filter(verdict='True Positive').count()),
            ('False Positives', qs.filter(verdict='False Positive').count()),
            ('SLA Breached', qs.filter(sla_status='Breached').count()),
        ]
    return headers, rows


def _write_csv(base, report, since, now, headers, rows, generated_by=None):
    filepath = os.path.join(REPORTS_DIR, f'{base}.csv')
    with open(filepath, 'w', newline='') as f:
        writer = csv.writer(f)
        writer.writerow(['Ariba SOC', report.name])
        writer.writerow(['Period', f'{since.strftime("%Y-%m-%d %H:%M")} to {now.strftime("%Y-%m-%d %H:%M")}'])
        writer.writerow(['Generated by', _generated_by_label(generated_by)])
        writer.writerow([])
        writer.writerow(headers)
        writer.writerows(rows)
    return filepath


def _write_excel(base, report, since, now, headers, rows, generated_by=None):
    filepath = os.path.join(REPORTS_DIR, f'{base}.xlsx')
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = report.get_report_type_display()[:31]
    ws.append(['Ariba SOC', report.name])
    ws.append([f'Period: {since.strftime("%Y-%m-%d")} to {now.strftime("%Y-%m-%d")}'])
    ws.append([f'Generated by: {_generated_by_label(generated_by)}'])
    ws.append([])
    ws.append(headers)
    for row in rows:
        ws.append(list(row))
    wb.save(filepath)
    return filepath


def _pdf_header_footer(generated_by_label, now):
    def draw(canvas, doc):
        canvas.saveState()
        width, height = A4

        # === HEADER ===
        # Dark navy top band
        canvas.setFillColor(colors.HexColor(BRAND_NAVY))
        canvas.rect(0, height - 28 * mm, width, 28 * mm, fill=True, stroke=False)

        # Blue accent line
        canvas.setFillColor(colors.HexColor(BRAND_ACCENT))
        canvas.rect(0, height - 29 * mm, width, 1.2 * mm, fill=True, stroke=False)

        # Company name
        canvas.setFont('Helvetica-Bold', 22)
        canvas.setFillColor(colors.white)
        canvas.drawString(20 * mm, height - 15 * mm, COMPANY_NAME)

        # Team name
        canvas.setFont('Helvetica', 9)
        canvas.setFillColor(colors.HexColor(BRAND_ACCENT))
        canvas.drawString(20 * mm, height - 21 * mm, TEAM_NAME)

        # SOC badge on right
        canvas.setFont('Helvetica-Bold', 10)
        canvas.setFillColor(colors.white)
        canvas.drawRightString(width - 20 * mm, height - 13 * mm, REPORT_TAGLINE)
        canvas.setFont('Helvetica', 7.5)
        canvas.setFillColor(colors.HexColor(BRAND_LIGHTGRAY))
        canvas.drawRightString(width - 20 * mm, height - 19 * mm, 'Confidential & Restricted')

        # === FOOTER ===
        # Light gray footer background
        canvas.setFillColor(colors.HexColor(BRAND_BG_LIGHT))
        canvas.rect(0, 0, width, 18 * mm, fill=True, stroke=False)

        # Top border line
        canvas.setStrokeColor(colors.HexColor(BRAND_BORDER))
        canvas.setLineWidth(0.5)
        canvas.line(20 * mm, 18 * mm, width - 20 * mm, 18 * mm)

        # Footer text
        canvas.setFont('Helvetica', 7)
        canvas.setFillColor(colors.HexColor(BRAND_GRAY))
        canvas.drawString(20 * mm, 12 * mm, f'{COMPANY_NAME} | {TEAM_NAME} | {REPORT_TAGLINE}')
        canvas.drawString(20 * mm, 7.5 * mm, f'Generated by {generated_by_label} on {now.strftime("%d %B %Y at %H:%M")}')

        # Page number
        canvas.setFont('Helvetica-Bold', 8)
        canvas.setFillColor(colors.HexColor(BRAND_NAVY))
        canvas.drawRightString(width - 20 * mm, 10 * mm, f'Page {canvas.getPageNumber()}')
        canvas.setFont('Helvetica', 6.5)
        canvas.setFillColor(colors.HexColor(BRAND_GRAY))
        canvas.drawRightString(width - 20 * mm, 7 * mm, 'This document is confidential and intended solely for authorized personnel.')

        canvas.restoreState()
    return draw


def _write_pdf(base, report, since, now, headers, rows, generated_by=None):
    filepath = os.path.join(REPORTS_DIR, f'{base}.pdf')
    doc = SimpleDocTemplate(
        filepath, pagesize=A4,
        topMargin=34 * mm, bottomMargin=24 * mm,
        leftMargin=20 * mm, rightMargin=20 * mm,
    )
    styles = getSampleStyleSheet()
    generated_by_label = _generated_by_label(generated_by)

    # Custom styles
    title_style = styles['Title']
    title_style.fontSize = 18
    title_style.textColor = colors.HexColor(BRAND_NAVY)
    title_style.spaceAfter = 2

    subtitle_style = styles['Normal']
    subtitle_style.fontSize = 9
    subtitle_style.textColor = colors.HexColor(BRAND_GRAY)
    subtitle_style.spaceAfter = 14

    elements = []

    # Report title
    elements.append(Paragraph(report.name, title_style))
    elements.append(Paragraph(
        f'{COMPANY_NAME} | {TEAM_NAME} | {REPORT_TAGLINE}',
        subtitle_style
    ))

    # Meta info table with professional styling
    meta_rows = [
        ['Report Type', report.get_report_type_display()],
        ['Schedule', report.get_schedule_display()],
        ['Reporting Period', f'{since.strftime("%d %B %Y")} to {now.strftime("%d %B %Y")}'],
        ['Generated By', generated_by_label],
        ['Date & Time', now.strftime('%d %B %Y at %H:%M')],
    ]
    meta_table = Table(meta_rows, colWidths=[40 * mm, 100 * mm], hAlign='LEFT')
    meta_table.setStyle(TableStyle([
        ('FONTNAME', (0, 0), (0, -1), 'Helvetica-Bold'),
        ('FONTNAME', (1, 0), (1, -1), 'Helvetica'),
        ('FONTSIZE', (0, 0), (-1, -1), 9),
        ('TEXTCOLOR', (0, 0), (0, -1), colors.HexColor(BRAND_NAVY)),
        ('TEXTCOLOR', (1, 0), (1, -1), colors.HexColor(BRAND_DARK)),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ('TOPPADDING', (0, 0), (-1, -1), 4),
        ('LINEBELOW', (0, -1), (-1, -1), 0.5, colors.HexColor(BRAND_BORDER)),
    ]))
    elements.append(meta_table)
    elements.append(Spacer(1, 16))

    # Data table
    table_data = [headers] + [[str(c) for c in row] for row in rows]
    table = Table(table_data, hAlign='LEFT')
    table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor(BRAND_NAVY)),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 0), (-1, 0), 9),
        ('GRID', (0, 0), (-1, -1), 0.4, colors.HexColor(BRAND_BORDER)),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor(BRAND_BG_LIGHT)]),
        ('FONTSIZE', (0, 1), (-1, -1), 8.5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ('TOPPADDING', (0, 0), (-1, -1), 6),
        ('LEFTPADDING', (0, 0), (-1, -1), 5),
        ('RIGHTPADDING', (0, 0), (-1, -1), 5),
        ('ALIGN', (0, 0), (-1, 0), 'CENTER'),
    ]))
    elements.append(table)

    if not rows:
        elements.append(Spacer(1, 12))
        no_data_style = styles['Normal']
        no_data_style.textColor = colors.HexColor(BRAND_GRAY)
        no_data_style.alignment = 1
        elements.append(Paragraph('No matching alerts found for the selected reporting period.', no_data_style))

    draw = _pdf_header_footer(generated_by_label, now)
    doc.build(elements, onFirstPage=draw, onLaterPages=draw)
    return filepath


def email_report(report, filepath):
    email = EmailMessage(
        subject=f'SOC Report: {report.name}',
        body='Please find attached your scheduled SOC report.',
        to=[report.recipient_email],
    )
    email.attach_file(filepath)
    email.send(fail_silently=True)


def generate_report(report, now=None, errors=None, generated_by=None):
    """Generate report's file for its current period, save it on the report,
    email it if a recipient is set, and return the relative media path
    (e.g. 'reports/x.pdf'), or None if generation failed. generated_by is the
    User who triggered generation (None for the automated scheduler)."""
    now = now or timezone.now()
    os.makedirs(REPORTS_DIR, exist_ok=True)
    since = now - timedelta(days=PERIOD_DAYS.get(report.schedule, 1))
    qs = _queryset(report, since)
    headers, rows = _rows(report, qs)

    stamp = now.strftime('%Y%m%d-%H%M%S')
    safe_name = ''.join(c if c.isalnum() or c in '-_' else '_' for c in report.name) or 'report'
    base = f'{safe_name}_{stamp}'

    if report.export_format == 'CSV':
        filepath = _write_csv(base, report, since, now, headers, rows, generated_by=generated_by)
    elif report.export_format == 'EXCEL':
        if not HAS_OPENPYXL:
            if errors is not None:
                errors.append('openpyxl not installed, cannot generate EXCEL report')
            return None
        filepath = _write_excel(base, report, since, now, headers, rows, generated_by=generated_by)
    else:
        if not HAS_REPORTLAB:
            if errors is not None:
                errors.append('reportlab not installed, cannot generate PDF report')
            return None
        filepath = _write_pdf(base, report, since, now, headers, rows, generated_by=generated_by)

    relative_path = os.path.relpath(filepath, settings.MEDIA_ROOT)
    if report.recipient_email:
        email_report(report, filepath)
    report.last_generated_at = now
    report.last_report_file = relative_path
    report.save(update_fields=['last_generated_at', 'last_report_file'])
    return relative_path
